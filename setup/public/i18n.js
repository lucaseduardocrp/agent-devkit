const DICTIONARIES = { 'en-US': enUS, 'pt-BR': ptBR };

export const LOCALES = [
  ['en-US', 'English'],
  ['pt-BR', 'Português (Brasil)'],
];

function initialLocale() {
  try {
    const saved = localStorage.getItem('adk-setup-locale');
    if (saved && DICTIONARIES[saved]) return saved;
  } catch {
    // Storage can be unavailable (private windows); fall back to the browser language.
  }
  return navigator.language?.toLowerCase().startsWith('pt') ? 'pt-BR' : 'en-US';
}

let locale = initialLocale();

export function getLocale() {
  return locale;
}

export function setLocale(next) {
  if (!DICTIONARIES[next]) return;
  locale = next;
  try {
    localStorage.setItem('adk-setup-locale', next);
  } catch {
    // Not persisted; the choice still applies to this visit.
  }
}

export function t(key, params = {}) {
  const template = DICTIONARIES[locale][key] ?? enUS[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}
