import { afterEach, describe, expect, it, vi } from 'vitest';
import { hookStepTexts, isQuickTunnelUrl, needsPolling } from '../src/features/e2e/e2e-types.js';
import { LocalHelperError, localTunnelBridge } from '../src/features/e2e/local-tunnel-bridge.js';

afterEach(() => vi.unstubAllGlobals());

describe('E2E type helpers', () => {
  it('recognizes quick tunnel URLs and rejects invalid addresses', () => {
    expect(isQuickTunnelUrl(' https://sample.trycloudflare.com/app ')).toBe(true);
    expect(isQuickTunnelUrl('https://app.example.com')).toBe(false);
    expect(isQuickTunnelUrl('not a url')).toBe(false);
  });

  it('polls active runs and publications in progress only', () => {
    expect(needsPolling({ status: 'running', lastReport: null })).toBe(true);
    expect(needsPolling({ status: 'completed', lastReport: null })).toBe(false);
    const report = {
      provider: 'testrail' as const,
      remoteRunId: null,
      url: null,
      publishedCases: 0,
      warnings: [],
      error: null,
      updatedAt: '2026-10-07T10:02:00Z',
    };
    expect(
      needsPolling({ status: 'completed', lastReport: { ...report, status: 'publishing' } }),
    ).toBe(true);
    expect(
      needsPolling({ status: 'completed', lastReport: { ...report, status: 'published' } }),
    ).toBe(false);
  });

  it('reads the steps of a Before Run or After Run from the numbered list in its first comment', () => {
    const hook = `// Generated by ADK
/**
 * Before Run steps:
 * 1. Create the employee "E2E TC001 - Ana" => The employee is created
 * 2. Create a Work Day event for that employee and edit
 *    its end date => The event shows the new end date
 * 3. Open the report
 *
 * Notes below the list are not steps.
 */
import { test } from '@playwright/test';
/* 1. Not a step: only the first comment with a list counts. */
export default async function beforeRun() {}`;
    expect(hookStepTexts(hook)).toEqual([
      {
        action: 'Create the employee "E2E TC001 - Ana"',
        expectedResult: 'The employee is created',
      },
      {
        action: 'Create a Work Day event for that employee and edit its end date',
        expectedResult: 'The event shows the new end date',
      },
      { action: 'Open the report', expectedResult: '' },
    ]);
    expect(hookStepTexts('export default async function afterRun() {}')).toEqual([]);
    expect(hookStepTexts(null)).toEqual([]);
  });
});

describe('local tunnel bridge failures', () => {
  it('reports a generic failure when the helper answers without a readable body', async () => {
    vi.stubGlobal(
      'fetch',
      vi.fn().mockResolvedValue({
        ok: false,
        json: () => Promise.reject(new SyntaxError('Unexpected end of JSON input')),
      }),
    );
    const failure = localTunnelBridge.stop();
    await expect(failure).rejects.toBeInstanceOf(LocalHelperError);
    await expect(failure).rejects.toMatchObject({
      code: 'failed',
      message: 'Local tunnel helper is unavailable.',
      name: 'LocalHelperError',
    });
  });
});
