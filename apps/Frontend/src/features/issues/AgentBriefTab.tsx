const levelVariant = {
  trivial: 'success',
  small: 'success',
  medium: 'warning',
  large: 'destructive',
  epic: 'destructive',
} as const;

function Section({
  title,
  locked,
  lockedLabel,
  children,
}: {
  title: string;
  locked: boolean;
  lockedLabel: string;
  children: ReactNode;
}) {
  return (
    <section className="space-y-3 rounded-lg border border-[var(--border)] bg-[var(--surface-2)] p-4">
      <div className="flex items-center justify-between gap-2">
        <h3 className="text-sm font-semibold">{title}</h3>
        {locked && (
          <Badge variant="outline" title={lockedLabel}>
            <i className="ti ti-lock mr-1" aria-hidden="true" />
            {lockedLabel}
          </Badge>
        )}
      </div>
      {children}
    </section>
  );
}

const sameJson = (a: unknown, b: unknown): boolean => JSON.stringify(a) === JSON.stringify(b);

export interface AgentBriefTabProps {
  apiClient: ApiClient;
  issueId: string;
  /** Changes whenever the issue is saved, so the brief the engine regenerated is fetched again. */
  issueVersion: string;
  isReadOnly?: boolean;
  /** Files already attached to the issue; the "read first" list picks from them. */
  issueAttachments?: readonly Attachment[];
  /** Goes to the module of a reference (Brain, PBIs, Issues, Specs, Test Plans). */
  onOpenModule?: (reference: BriefReference) => void;
}

const NO_ATTACHMENTS: readonly Attachment[] = [];

export function AgentBriefTab({
  apiClient,
  issueId,
  issueVersion,
  isReadOnly = false,
  issueAttachments = NO_ATTACHMENTS,
  onOpenModule,
}: AgentBriefTabProps) {
  const { locale } = useI18n();
  const t = copy[locale];
  const [brief, setBrief] = useState<IssueAgentBrief | null>(null);
  const [draft, setDraft] = useState<IssueAgentBrief | null>(null);
  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  const [copied, setCopied] = useState(false);
  /** Files sent from this tab; they join the issue attachments when the brief is saved. */
  const [uploaded, setUploaded] = useState<readonly Attachment[]>([]);
  const attachedIds = useRef(new Set<string>());

  const uploadFile = useCallback(
    async (file: File) => {
      const attachment = await apiClient.uploadAttachment('issue', file);
      setUploaded((current) => [...current, attachment]);
      return attachment;
    },
    [apiClient],
  );

  const apply = useCallback((next: IssueAgentBrief | null) => {
    setBrief(next);
    setDraft(next ? structuredClone(next) : null);
  }, []);

  const load = useCallback(
    async (signal?: AbortSignal) => {
      setLoading(true);
      setError('');
      try {
        apply(await apiClient.getIssueBrief(issueId, signal));
      } catch (caught) {
        if (signal?.aborted) return;
        setError(caught instanceof Error ? caught.message : t.failed);
      } finally {
        if (!signal?.aborted) setLoading(false);
      }
    },
    [apiClient, apply, issueId, t.failed],
  );

  useEffect(() => {
    const controller = new AbortController();
    void load(controller.signal);
    return () => controller.abort();
  }, [load, issueVersion]);

  const run = async (action: () => Promise<IssueAgentBrief>) => {
    setBusy(true);
    setError('');
    try {
      apply(await action());
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : t.failed);
    } finally {
      setBusy(false);
    }
  };

  if (loading) return <AgentBriefSkeleton label={t.loading} />;

  if (!brief || !draft)
    return (
      <div className="space-y-3 py-6 text-center text-sm text-[var(--text-muted)]">
        {error && (
          <p role="alert" className="text-red-300">
            {error}
          </p>
        )}
        <p>{t.empty}</p>
        <div className="flex justify-center gap-2">
          <Button type="button" variant="outline" onClick={() => void load()}>
            {t.retry}
          </Button>
          {!isReadOnly && (
            <Button
              type="button"
              isLoading={busy}
              onClick={() => void run(() => apiClient.regenerateIssueBrief(issueId))}
            >
              {t.generate}
            </Button>
          )}
        </div>
      </div>
    );

  const isLocked = (field: BriefEditableField) => brief.locked.includes(field);
  const patch = (changes: Partial<IssueAgentBrief>) => setDraft({ ...draft, ...changes });
  const changeProvider = (provider: string) => {
    const { model } = draft.recommendation;
    // Picking a listed provider swaps in a model it offers; typing a custom one keeps the model.
    const listed = providerChoices().some((option) => option.value === provider);
    const keep = !listed || modelChoices(provider).some((option) => option.value === model);
    patch({
      recommendation: {
        ...draft.recommendation,
        provider,
        model: keep ? model : defaultModelFor(provider),
      },
    });
  };

  /** Files used by a reference that the issue does not have yet are attached before saving. */
  const attachReferencedUploads = async () => {
    const used = new Set(
      draft.readFirst
        .filter((item) => item.kind === 'attachment' || item.kind === 'file')
        .map((item) => item.ref),
    );
    const pending = uploaded.filter(
      (file) => used.has(file.id) && !attachedIds.current.has(file.id),
    );
    if (!pending.length) return;
    const known = new Set(issueAttachments.map((file) => file.id));
    const keep = uploaded.filter((file) => attachedIds.current.has(file.id));
    await apiClient.updateIssue(issueId, {
      attachments: [
        ...issueAttachments,
        ...[...keep, ...pending].filter((file) => !known.has(file.id)),
      ],
    });
    for (const file of pending) attachedIds.current.add(file.id);
  };

  const saveBrief = async () => {
    await attachReferencedUploads();
    return apiClient.updateIssueBrief(issueId, edits);
  };

  const edits: IssueAgentBriefEdits = {};
  const fields: BriefEditableField[] = [
    'recommendation',
    'readFirst',
    'considerations',
    'prompt',
    'budget',
  ];
  for (const field of fields)
    if (!sameJson(draft[field], brief[field])) Object.assign(edits, { [field]: draft[field] });
  const dirty = Object.keys(edits).length > 0;
  const disabled = isReadOnly || busy;

  const copyPrompt = async () => {
    try {
      await navigator.clipboard.writeText(fullPrompt(draft.prompt));
      setCopied(true);
    } catch {
      setError(t.failed);
    }
  };

  return (
    <div className="space-y-4" data-testid="agent-brief">
      <p className="text-sm text-[var(--text-muted)]">{t.intro}</p>
      {error && (
        <p role="alert" className="text-sm text-red-300">
          {error}
        </p>
      )}

      <Section title={t.complexity} locked={false} lockedLabel={t.locked}>
        <div className="flex flex-wrap items-center gap-2">
          <Badge variant={levelVariant[brief.complexity.level]}>
            {t.levels[brief.complexity.level]}
          </Badge>
          <span className="text-sm">
            {t.score}: {brief.complexity.score}/10
          </span>
        </div>
        {brief.complexity.signals.length > 0 && (
          <ul className="list-disc space-y-1 pl-5 text-xs text-[var(--text-muted)]">
            {brief.complexity.signals.map((signal) => (
              <li key={signal}>{signal}</li>
            ))}
          </ul>
        )}
      </Section>

      <Section title={t.recommendation} locked={isLocked('recommendation')} lockedLabel={t.locked}>
        <div className="grid gap-3 sm:grid-cols-3">
          <div className="space-y-1 text-sm">
            <span>{t.provider}</span>
            <ChoiceField
              label={t.provider}
              placeholder={t.providerPlaceholder}
              emptyMessage={t.noMatch}
              disabled={disabled}
              value={draft.recommendation.provider}
              options={providerChoices(draft.recommendation.provider)}
              onChange={changeProvider}
            />
          </div>
          <div className="space-y-1 text-sm">
            <span>{t.model}</span>
            <ChoiceField
              label={t.model}
              placeholder={t.modelPlaceholder}
              emptyMessage={t.noMatch}
              disabled={disabled}
              value={draft.recommendation.model}
              options={modelChoices(draft.recommendation.provider)}
              onChange={(model) => patch({ recommendation: { ...draft.recommendation, model } })}
            />
          </div>
          <label className="space-y-1 text-sm">
            <span>{t.effort}</span>
            <Select
              disabled={disabled}
              value={draft.recommendation.effort}
              onChange={(event) =>
                patch({
                  recommendation: {
                    ...draft.recommendation,
                    effort: event.target.value as BriefEffort,
                  },
                })
              }
            >
              {BRIEF_EFFORTS.map((effort) => (
                <option key={effort} value={effort}>
                  {t.efforts[effort]}
                </option>
              ))}
            </Select>
          </label>
        </div>
        <p className="text-xs text-[var(--text-muted)]">{t.modelHint}</p>
        <p className="text-sm">
          <span className="font-medium">{t.rationale}: </span>
          {brief.recommendation.rationale}
        </p>
        <p className="text-sm">
          <span className="font-medium">{t.cost}: </span>
          {brief.recommendation.estimatedCostUsd === null
            ? t.noCost
            : `US$ ${brief.recommendation.estimatedCostUsd.toFixed(4)}`}
        </p>
        {brief.recommendation.alternatives.length > 0 && (
          <div className="space-y-1">
            <h4 className="text-xs font-semibold uppercase text-[var(--text-muted)]">
              {t.alternatives}
            </h4>
            <ul className="space-y-1 text-xs">
              {brief.recommendation.alternatives.map((alternative) => (
                <li key={`${alternative.provider}/${alternative.model}/${alternative.effort}`}>
                  <span className="font-mono">
                    {alternative.provider}/{alternative.model}
                  </span>{' '}
                  · {t.efforts[alternative.effort]} · {alternative.reason}
                </li>
              ))}
            </ul>
          </div>
        )}
      </Section>

      <Section title={t.readFirst} locked={isLocked('readFirst')} lockedLabel={t.locked}>
        {draft.readFirst.length === 0 && (
          <p className="text-xs text-[var(--text-muted)]">{t.noReferences}</p>
        )}
        <ReferencesEditor
          apiClient={apiClient}
          issueId={issueId}
          items={draft.readFirst}
          onChange={(readFirst) => patch({ readFirst })}
          disabled={disabled}
          readOnly={isReadOnly}
          issueAttachments={issueAttachments}
          uploaded={uploaded}
          onUpload={uploadFile}
          addLabel={t.addReference}
          {...(onOpenModule ? { onOpenModule } : {})}
        />
      </Section>

      <Section title={t.considerations} locked={isLocked('considerations')} lockedLabel={t.locked}>
        {draft.considerations.length === 0 && (
          <p className="text-xs text-[var(--text-muted)]">{t.noConsiderations}</p>
        )}
        {draft.considerations.map((item, index) => (
          <div
            // Plain strings edited in place: the position is the only identity they have.
            key={index}
            className="flex items-center gap-2"
          >
            <Input
              aria-label={`${t.consideration} ${index + 1}`}
              disabled={disabled}
              value={item}
              onChange={(event) =>
                patch({
                  considerations: draft.considerations.map((value, position) =>
                    position === index ? event.target.value : value,
                  ),
                })
              }
            />
            <Button
              type="button"
              variant="ghost"
              size="icon"
              className="text-red-400 hover:text-red-300"
              disabled={disabled}
              aria-label={`${t.removeConsideration} ${index + 1}`}
              onClick={() =>
                patch({
                  considerations: draft.considerations.filter((_, position) => position !== index),
                })
              }
            >
              <i className="ti ti-trash" aria-hidden="true" />
            </Button>
          </div>
        ))}
        {!isReadOnly && (
          <Button
            type="button"
            variant="outline"
            disabled={busy}
            onClick={() => patch({ considerations: [...draft.considerations, ''] })}
          >
            <i className="ti ti-plus" aria-hidden="true" />
            {t.addConsideration}
          </Button>
        )}
      </Section>

      <Section title={t.prompt} locked={isLocked('prompt')} lockedLabel={t.locked}>
        <PromptEditor
          prompt={draft.prompt}
          original={brief.prompt}
          maxInputTokens={draft.budget.maxInputTokens}
          disabled={disabled}
          onChange={(prompt) => patch({ prompt })}
          onCopy={() => void copyPrompt()}
          copied={copied}
        />
      </Section>

      <Section title={t.budget} locked={isLocked('budget')} lockedLabel={t.locked}>
        <div className="grid gap-3 sm:grid-cols-2">
          {(['maxInputTokens', 'maxOutputTokens'] as const).map((key) => (
            <label key={key} className="space-y-1 text-sm">
              <span>{t[key]}</span>
              <Input
                type="number"
                min={0}
                disabled={disabled}
                value={draft.budget[key]}
                onChange={(event) =>
                  patch({
                    budget: {
                      ...draft.budget,
                      [key]: Math.max(0, Number(event.target.value) || 0),
                    },
                  })
                }
              />
            </label>
          ))}
        </div>
      </Section>

      <div className="flex flex-wrap items-center justify-between gap-3">
        <p className="text-xs text-[var(--text-muted)]">
          {brief.source === 'edited' ? t.edited : t.autoGenerated} · {t.generatedAt}{' '}
          {new Date(brief.generatedAt).toLocaleString(locale)}
        </p>
        {!isReadOnly && (
          <div className="flex flex-wrap gap-2">
            <Button
              type="button"
              variant="ghost"
              disabled={busy}
              title={t.restoreHint}
              onClick={() => void run(() => apiClient.regenerateIssueBrief(issueId, true))}
            >
              <i className="ti ti-restore" aria-hidden="true" />
              {t.restore}
            </Button>
            <Button
              type="button"
              variant="outline"
              disabled={busy}
              title={t.regenerateHint}
              onClick={() => void run(() => apiClient.regenerateIssueBrief(issueId))}
            >
              <i className="ti ti-refresh" aria-hidden="true" />
              {t.regenerate}
            </Button>
            <Button
              type="button"
              disabled={!dirty || busy}
              isLoading={busy}
              onClick={() => void run(saveBrief)}
            >
              {t.save}
            </Button>
          </div>
        )}
      </div>
    </div>
  );
}
